#!/usr/bin/env python3
"""
pl_images.py — the secondary listing images, generated by Qwen from the real product photo.

WHY THE MAIN IMAGE IS NOT GENERATED
-----------------------------------
Amazon's image policy requires the MAIN image to be an actual photograph of the actual product
on a pure white background. A generated main image is the single fastest way to have a new ASIN
suppressed, and it is the one image a suppression cannot be argued out of. So 01_main.jpg stays
what build_pl_listings.py already makes: the real Zoro photograph, framed on white, with the
HOANK wordmark. Everything from 02 onward — the shots that actually sell, and where Amazon
allows lifestyle and infographic content — is generated here.

WHY EDIT MODE AND NOT TEXT-TO-IMAGE
-----------------------------------
A prompt-only model invents a product that merely resembles ours, and a buyer who receives
something that does not match the photo files an INAD return. So every shot is generated in
edit / subject-consistency mode with the real product photo as the reference image: the model
keeps the actual item and changes only the scene around it.

    python3 pl_images.py --sku HOA-Kam-G4120751-500          # generate for one built listing
    python3 pl_images.py --all --limit 3                     # every built listing, 3 shots each
    python3 pl_images.py --sku ... --dry-run                 # print the prompts, spend nothing

Needs DASHSCOPE_API_KEY (or QWEN_API_KEY) — see .env.example. Each shot is billed per image.
"""
import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
AUTO = os.path.dirname(HERE)
ROOT = os.path.dirname(AUTO)
OUT = os.path.join(HERE, "out_pl")
SKILL = os.path.join(ROOT, "agent", "skills", "qwencloud-image-generation", "scripts", "image.py")
MODEL = "wan2.7-image-pro"          # keeps the subject from reference_images; 2K output

sys.path.insert(0, HERE)
import pl_store                                        # noqa: E402

# A generated photo has to look like a photograph of OUR item, not like AI art. Everything below
# pushes the model toward catalogue photography and away from the things that make a listing
# image obviously synthetic — invented text above all, which Amazon also treats as a claim.
NEGATIVE = ("text, words, letters, numbers, watermark, logo, brand name, signage, packaging copy, "
            "deformed product, duplicated product, extra objects, distorted proportions, "
            "blurry, low quality, oversaturated, cartoon, illustration, 3d render, cgi")

STYLE = "professional commercial product photography, photorealistic, sharp focus, true-to-life colour"

# Where this kind of product is actually used. Falls back to a neutral workspace.
SETTINGS = {
    "Shipping & Packing Supplies": "a tidy shipping and packing bench in a small warehouse",
    "Filing & Organization": "a clean modern office desk",
    "Medical Equipment": "a clean clinical examination room",
    "Lawn & Garden": "a sunny garden with young trees",
    "Canopies, Coverings & Outdoor Structures": "an outdoor work yard on an overcast day",
    "Cleaning Supplies": "a bright commercial janitorial supply room",
}
DEFAULT_SETTING = "a clean, well-lit professional workspace"

SHOTS = [
    ("02_in_use",
     "the exact product from the reference image being used by a pair of hands in {setting}, "
     "natural daylight from the side, shallow depth of field, the product in sharp focus"),
    ("03_detail",
     "extreme close-up of the exact product from the reference image, showing its material and "
     "build quality, soft studio lighting, plain neutral background, macro photography"),
    ("04_scale",
     "the exact product from the reference image resting on a clean surface in {setting} beside "
     "ordinary everyday objects that show its size, soft even lighting, uncluttered composition"),
    ("05_in_place",
     "wide shot of the exact product from the reference image in use in {setting}, bright natural "
     "light, tidy and uncluttered, the product clearly the subject of the photograph"),
]


def load_key():
    """Return the key without ever printing it. .env first, then the environment."""
    for path in (os.path.join(ROOT, ".env"), os.path.join(AUTO, ".env"), os.path.join(HERE, ".env")):
        if not os.path.exists(path):
            continue
        for line in open(path, encoding="utf-8", errors="replace"):
            line = line.strip()
            if line.startswith(("DASHSCOPE_API_KEY=", "QWEN_API_KEY=")):
                val = line.split("=", 1)[1].strip().strip('"').strip("'")
                if val and not val.startswith("sk-your-key"):
                    return val
    return os.environ.get("DASHSCOPE_API_KEY") or os.environ.get("QWEN_API_KEY") or ""


def prompt_for(shot_prompt, data, setting):
    """The shot, the product, and the style — in that order, which is the formula the model wants."""
    # The listing title ends with the Amazon category ("... — Shipping & Packing Supplies").
    # That belongs on the listing, not in a photograph's description, where it only confuses
    # the model about what object it is looking at.
    name = (data.get("title") or "").replace("HOANK ", "", 1).split(" \u2014 ")[0].strip()
    pack = data.get("pack") or 1
    what = f"{name}" + (f", a pack of {pack}" if pack > 1 else "")
    return (f"{shot_prompt.format(setting=setting)}. The product is {what}. "
            f"Keep the product identical to the reference image — same shape, colour, proportions "
            f"and markings. {STYLE}.")


def generate(sku, folder, data, shots, dry_run=False, key=""):
    photo = os.path.join(folder, "images", "01_main.jpg")
    if not os.path.exists(photo):
        print(f"  {sku}: no 01_main.jpg to work from — build the listing first")
        return 0
    setting = SETTINGS.get(data.get("category") or "", DEFAULT_SETTING)
    env = os.environ.copy()
    if key:
        env["DASHSCOPE_API_KEY"] = key
    made = 0
    for fname, shot in shots:
        dest = os.path.join(folder, "images", f"{fname}.jpg")
        body = {
            "prompt": prompt_for(shot, data, setting),
            "reference_images": [photo],
            "negative_prompt": NEGATIVE,
            "n": 1,
            "size": "2K",              # Amazon wants the longest side >= 1600px
            "watermark": False,
        }
        if dry_run:
            print(f"\n  {sku} → {fname}.jpg\n    {body['prompt']}")
            made += 1
            continue
        cmd = [sys.executable, SKILL, "--model", MODEL,
               "--request", json.dumps(body), "--output", dest]
        r = subprocess.run(cmd, capture_output=True, text=True, env=env, cwd=HERE)
        ok = r.returncode == 0 and os.path.exists(dest) and os.path.getsize(dest) > 0
        if ok:
            made += 1
            print(f"  ✓ {sku} {fname}.jpg")
        else:
            err = (r.stderr or r.stdout or "").strip().splitlines()
            print(f"  ✗ {sku} {fname}.jpg — {err[-1] if err else 'no output'}")
        for line in (r.stderr or "").splitlines():
            if "[ACTION_REQUIRED]" in line or "[UPDATE_AVAILABLE]" in line:
                print(f"    note: {line.strip()}")
    return made


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sku", default="", help="one built listing, by SKU")
    ap.add_argument("--all", action="store_true", help="every listing already built")
    ap.add_argument("--limit", type=int, default=len(SHOTS),
                    help=f"how many shots per product (1-{len(SHOTS)}; each one is billed)")
    ap.add_argument("--dry-run", action="store_true", help="print the prompts, call nothing")
    a = ap.parse_args()

    if not os.path.exists(SKILL):
        sys.exit(f"qwencloud-image-generation skill not found at {SKILL}")

    key = load_key()
    if not key and not a.dry_run:
        sys.exit("No DASHSCOPE_API_KEY / QWEN_API_KEY found.\n"
                 "  Put it in a .env at the repo root:  DASHSCOPE_API_KEY=sk-...\n"
                 "  Get one from https://home.qwencloud.com/api-keys\n"
                 "  (--dry-run prints the prompts without needing a key.)")

    skus = []
    if a.sku:
        skus = [a.sku]
    elif a.all:
        skus = sorted(d for d in os.listdir(OUT)
                      if os.path.isdir(os.path.join(OUT, d)) and not d.startswith("_"))
    else:
        sys.exit("Pass --sku <SKU> or --all.")

    shots = SHOTS[:max(1, min(a.limit, len(SHOTS)))]
    total = 0
    for sku in skus:
        folder = os.path.join(OUT, sku)
        dj = os.path.join(folder, "data.json")
        if not os.path.exists(dj):
            print(f"  {sku}: no data.json — not a built listing")
            continue
        data = json.load(open(dj, encoding="utf-8"))
        n = generate(sku, folder, data, shots, a.dry_run, key)
        total += n
        if n and not a.dry_run:
            data["ai_images"] = n
            json.dump(data, open(dj, "w", encoding="utf-8"), indent=1)
            try:
                pl_store.mark_images(data.get("zoro_no", ""), n)
            except Exception as e:
                print(f"    (DB not updated: {type(e).__name__}: {e})")

    verb = "would generate" if a.dry_run else "generated"
    print(f"\n  {verb} {total} image(s) across {len(skus)} listing(s)")


if __name__ == "__main__":
    main()
